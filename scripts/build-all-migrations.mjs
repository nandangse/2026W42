// Regenerates supabase/ALL_MIGRATIONS.sql by concatenating every numbered
// migration in order.
//
// Why this exists: ALL_MIGRATIONS.sql is hand-maintained no longer. It had
// silently fallen three migrations behind (it stopped at 0017 while 0018-0020
// existed), which is the worst possible failure for a file whose entire job is
// to be the trustworthy "paste this and you're current" artefact.
//
//   npm run build:migrations
//
// Run it whenever you add a migration. The output is pure concatenation — the
// numbered files stay the source of truth, and each is idempotent, so the
// combined file is too.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "supabase", "migrations");
const out = join(root, "supabase", "ALL_MIGRATIONS.sql");

const files = readdirSync(dir)
  .filter((f) => /^\d{4}_.*\.sql$/.test(f))
  .sort();

if (!files.length) {
  console.error("No migrations found in " + dir);
  process.exit(1);
}

const parts = [
  "-- ============================================================",
  "-- Nandan Works Planning Suite — ALL migrations, in order.",
  "-- Paste into Supabase → SQL Editor → Run. Safe to re-run.",
  "--",
  "-- GENERATED by scripts/build-all-migrations.mjs — do not hand-edit.",
  "-- Edit the numbered files in supabase/migrations/ and regenerate:",
  "--   npm run build:migrations",
  "-- ============================================================",
  "",
  "",
];

for (const f of files) {
  parts.push(`-- >>>>> supabase/migrations/${f}`);
  parts.push(readFileSync(join(dir, f), "utf8").replace(/\s+$/, ""));
  parts.push("");
  parts.push("");
}

writeFileSync(out, parts.join("\n").replace(/\n{3,}$/, "\n"));
console.log(`ALL_MIGRATIONS.sql rebuilt from ${files.length} migrations:`);
console.log("  " + files.join("\n  "));
