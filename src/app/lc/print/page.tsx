import type { Metadata } from "next";
import { redirect } from "next/navigation";
import { currentUser, RAGHU_EMAIL } from "@/lib/auth";
import { adminClient } from "@/lib/supabase/admin";
import { lcMembers } from "@/lib/lc/auth";
import SscPrint from "@/components/lc/SscPrint";

export const dynamic = "force-dynamic";
export const metadata: Metadata = { title: "Start · Stop · Continue — Leaders Council" };

/**
 * /lc/print — the Start · Stop · Continue board as a document: one page for
 * Start, one for Stop, one for Continue, a page break between (Dr Raghu,
 * 10 Oct 2026: "Print PDF … with a page break each, and that PDF is only to
 * be generated by Raghu, nobody else"). The owner alone; everyone else is
 * sent back to the board. The browser's print dialog saves it as PDF.
 */
export default async function SscPrintPage() {
  const user = await currentUser();
  if (!user || user.disabled) redirect("/login");
  if (!user.isOwner) redirect("/lc#ssc");
  const admin = adminClient();
  const [{ data: cards }, { data: reactions }, members] = await Promise.all([
    admin.from("lc_ssc").select("*").order("created_at"),
    admin.from("lc_reaction").select("ref_id,value").eq("ref_kind", "ssc"),
    lcMembers(admin, RAGHU_EMAIL),
  ]);
  const rows = (cards || []).map((c) => ({
    ...c,
    up: (reactions || []).filter((r) => r.ref_id === c.id && r.value === "up").length,
    down: (reactions || []).filter((r) => r.ref_id === c.id && r.value === "down").length,
  }));
  return <SscPrint cards={rows} members={members} />;
}
