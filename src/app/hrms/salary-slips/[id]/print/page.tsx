import type { Metadata } from "next";
import * as XLSX from "xlsx";
import { currentUser } from "@/lib/auth";
import { adminClient } from "@/lib/supabase/admin";
import { resolveHrmsAccess } from "@/lib/hrms";
import { extractSlips, pickSamples, slipsFromRegister } from "@/lib/salary-slip";
import { people } from "@/lib/hrms-wa";
import SalarySlipsPrint from "@/components/hrms/SalarySlipsPrint";

export const dynamic = "force-dynamic";
export const metadata: Metadata = { title: "Nandan HRMS Genie" };

/**
 * /hrms/salary-slips/<sheetId>/print — A5 salary slips off the month's file.
 *
 *   ?samples=1   — nine by money band (worker 10–30k, staff 20k–1.5L+) and
 *                  four by shape: a loan deduction, an advance, a Labour -
 *                  Contract and a Contractor (Dr Raghu, 7 Sep 2026), because
 *                  the bands sample by money and can miss the slips whose
 *                  SHAPE is what goes wrong
 *   ?emp=6972    — one person's slip
 *   (neither)    — every slip in the file, one A5 page each
 *
 * The layout follows the July 2026 Word slip verbatim, minus the line
 * Dr Raghu ordered off it (OT / Comp Off / Late Mark / Late Deduction).
 * Every figure is read from the uploaded sheet itself.
 */
export default async function SalarySlipsPage({ params, searchParams }: {
  params: { id: string };
  searchParams: { samples?: string; emp?: string };
}) {
  const user = await currentUser();
  const allowed =
    !!user && !user.disabled && (await resolveHrmsAccess(adminClient(), user.email, user.isOwner));
  if (!allowed) {
    return (
      <div style={{ padding: 40, fontFamily: "system-ui, sans-serif" }}>
        <h1 style={{ fontSize: 20 }}>You are not authorized to view this Page - Login at the right page</h1>
      </div>
    );
  }

  const admin = adminClient();
  const { data: sheet } = await admin
    .from("hrms_salary_sheet").select("id, month, year, file_path, file_name, status, generated_at, rows").eq("id", params.id).maybeSingle();
  if (!sheet) return <div style={{ padding: 40, fontFamily: "system-ui" }}>No such salary sheet.</div>;
  // A month generated by the payroll run reads its rows — comp off and all.
  // A month uploaded as a file is read off the file, as before.
  const generated = Array.isArray(sheet.rows) && sheet.rows.length > 0 && !!sheet.generated_at;
  let slips: ReturnType<typeof extractSlips>;
  if (generated) {
    const rows = sheet.rows as { employee_id: string }[];
    const ppl = await people(admin, rows.map((r) => String(r.employee_id)));
    const byId = new Map(ppl.map((p) => [p.id, p.value as Record<string, unknown>]));
    slips = slipsFromRegister(rows, (id) => byId.get(id) || null, new Date(Date.UTC(Number(sheet.year), Number(sheet.month), 0)).getUTCDate());
  } else {
    if (!sheet.file_path) return <div style={{ padding: 40, fontFamily: "system-ui" }}>No stored file for this month.</div>;
    const { data: blob, error } = await admin.storage.from("voice-notes").download(String(sheet.file_path));
    if (error || !blob) return <div style={{ padding: 40, fontFamily: "system-ui" }}>Could not fetch the stored file: {error?.message}</div>;
    const wb = XLSX.read(Buffer.from(await blob.arrayBuffer()), { type: "buffer", raw: false });
    const ws = wb.Sheets[wb.SheetNames[0]];
    const grid = XLSX.utils.sheet_to_json(ws, { header: 1, defval: "", blankrows: false }) as unknown[][];
    slips = extractSlips(grid);
  }

  // THE SINGLE FILE HAPPENS AFTER THE FREEZE (Dr Raghu, 27 Aug 2026): the
  // full run is the document that goes into 205 Drive folders, and a draft
  // month can still change under it. Samples and single slips stay open in
  // draft — watermarked — so a few can be eyeballed each month.
  if (!searchParams.samples && !searchParams.emp && sheet.status !== "Frozen") {
    return (
      <div style={{ padding: 40, fontFamily: "system-ui, sans-serif", maxWidth: 560 }}>
        <h2 style={{ fontSize: 18 }}>This month is not frozen yet.</h2>
        <p style={{ color: "var(--dim)", lineHeight: 1.6 }}>
          The full slip run is printed only after RJ freezes the month — it is the file that goes into every
          employee&apos;s folder, and a draft can still change under it. Use <b>Draft samples</b> to eyeball
          a few slips meanwhile.
        </p>
      </div>
    );
  }

  let picked: { label: string | null; slip: NonNullable<ReturnType<typeof extractSlips>>[number] }[];
  if (searchParams.samples) {
    picked = pickSamples(slips)
      .filter((x): x is { label: string; slip: NonNullable<(typeof x)["slip"]> } => !!x.slip)
      .map((x) => ({ label: x.label, slip: x.slip }));
  } else if (searchParams.emp) {
    picked = slips.filter((s) => s.id === String(searchParams.emp)).map((s) => ({ label: null, slip: s }));
  } else {
    picked = slips.map((s) => ({ label: null, slip: s }));
  }

  return <SalarySlipsPrint month={sheet.month} year={sheet.year} picked={picked} total={slips.length} draft={sheet.status !== "Frozen"} />;
}
